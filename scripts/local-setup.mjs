// pnpm local:setup — check prerequisites and create/complete the Git-ignored .env.
// Plain Node (no shell syntax) so it behaves the same in PowerShell, cmd, and WSL2.
// Never overwrites an existing value and never prints secret values.
import { spawnSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const examplePath = resolve(root, '.env.example');
const envPath = resolve(root, '.env');
const problems = [];

// Windows needs a shell to run pnpm.cmd; arguments here are constants, never user input.
function run(command, args) {
  const result =
    process.platform === 'win32'
      ? spawnSync([command, ...args].join(' '), { encoding: 'utf8', shell: true })
      : spawnSync(command, args, { encoding: 'utf8' });
  return { ok: result.status === 0, out: (result.stdout ?? '').trim() };
}

// --- Prerequisites ---------------------------------------------------------
const [major, minor] = process.versions.node.split('.').map(Number);
if (major !== 24 || minor < 15) {
  problems.push(`Node ${process.versions.node} found; this project needs Node 24 (>= 24.15).`);
} else {
  console.log(`ok   Node ${process.versions.node}`);
}

const wantedPnpm = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8')).packageManager.split(
  '@',
)[1];
const pnpm = run('pnpm', ['--version']);
if (!pnpm.ok) problems.push(`pnpm not found. Install it with: npm install --global pnpm@${wantedPnpm}`);
else if (pnpm.out !== wantedPnpm) console.log(`warn pnpm ${pnpm.out} found; the project pins ${wantedPnpm}.`);
else console.log(`ok   pnpm ${pnpm.out}`);

const docker = run('docker', ['info', '--format', '{{.ServerVersion}}']);
if (!docker.ok) problems.push('Docker is not running. Start Docker Desktop (WSL2 backend) and re-run.');
else console.log(`ok   Docker engine ${docker.out}`);

const compose = run('docker', ['compose', 'version', '--short']);
if (!compose.ok) problems.push('Docker Compose v2 not found (it ships with Docker Desktop).');
else console.log(`ok   Docker Compose ${compose.out}`);

// --- .env ------------------------------------------------------------------
const parse = (text) =>
  new Map(
    text
      .split(/\r?\n/)
      .filter((line) => /^[A-Z0-9_]+=/.test(line))
      .map((line) => [line.slice(0, line.indexOf('=')), line.slice(line.indexOf('=') + 1)]),
  );

const example = parse(readFileSync(examplePath, 'utf8'));
const existingText = existsSync(envPath) ? readFileSync(envPath, 'utf8') : '';
const existing = parse(existingText);
const values = new Map(existing);
const added = [];

// Pass 1: plain and generated values; pass 2: ${NAME} references to them.
for (const pass of [1, 2]) {
  for (const [key, template] of example) {
    if (values.has(key)) continue;
    const isReference = template.includes('${');
    if (pass === 1 && isReference) continue;
    let value = template;
    if (template === '__GENERATE__') value = randomBytes(32).toString('hex');
    if (isReference) {
      value = template.replace(/\$\{([A-Z0-9_]+)\}/g, (_, name) => {
        if (!values.has(name)) throw new Error(`.env.example references unknown ${name}`);
        return values.get(name);
      });
    }
    values.set(key, value);
    added.push(key);
  }
}

if (added.length === 0) {
  console.log('ok   .env already complete (nothing changed)');
} else {
  const prefix = existingText === '' ? '# Generated by pnpm local:setup. Never commit this file.\n' : '';
  const separator = existingText !== '' && !existingText.endsWith('\n') ? '\n' : '';
  const lines = added.map((key) => `${key}=${values.get(key)}`).join('\n');
  writeFileSync(envPath, `${existingText}${separator}${prefix}${lines}\n`, { mode: 0o600 });
  console.log(`ok   .env ${existingText === '' ? 'created' : 'completed'}; added: ${added.join(', ')}`);
}

// --- No telemetry from the local toolchain ---------------------------------
if (pnpm.ok) run('pnpm', ['--filter', '@trp/web', 'exec', 'next', 'telemetry', 'disable']);

if (problems.length > 0) {
  console.error(`\nSetup incomplete:\n- ${problems.join('\n- ')}`);
  process.exit(1);
}
console.log('\nNext: pnpm infra:up, then pnpm dev, then open http://localhost:8080');
