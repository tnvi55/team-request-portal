// Runs as part of `generate`: writes src/generated/migrations.ts with the committed migration
// names, so the API (and its Docker image) knows which migrations readiness must find applied.
import { readdirSync, writeFileSync } from 'node:fs';

const names = (kind) =>
  readdirSync(new URL(`./${kind}/migrations/`, import.meta.url), { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

const source = `// Generated by prisma/list-migrations.mjs during \`generate\`. Do not edit.
export const CONTROL_MIGRATIONS: readonly string[] = ${JSON.stringify(names('control'))};
export const TENANT_MIGRATIONS: readonly string[] = ${JSON.stringify(names('tenant'))};
`;
writeFileSync(new URL('../src/generated/migrations.ts', import.meta.url), source);
